param([string]$ZipPath)
$ErrorActionPreference = 'Stop'
$workspace = [IO.Path]::GetFullPath((Split-Path $PSScriptRoot -Parent))
if (-not $ZipPath) {
    $appVersion = ([xml][IO.File]::ReadAllText((Join-Path $workspace 'Directory.Build.props'))).Project.PropertyGroup.Version
    $ZipPath = Join-Path $workspace ('artifacts\GitCompass-' + $appVersion + '-win-x64.zip')
}
$zip = [IO.Path]::GetFullPath($ZipPath)
$expected = ([IO.File]::ReadAllText($zip + '.sha256').Trim() -split '\s+')[0]
if ((Get-FileHash -LiteralPath $zip -Algorithm SHA256).Hash -ne $expected) { throw 'Package ZIP checksum mismatch.' }
$testRoot = Join-Path $workspace ('.artifacts\package-check-' + [guid]::NewGuid().ToString('N'))
$extracted = Join-Path $testRoot 'extracted'
Expand-Archive -LiteralPath $zip -DestinationPath $extracted
$manifest = [IO.File]::ReadAllText((Join-Path $extracted 'package-manifest.json')) | ConvertFrom-Json
foreach ($file in $manifest.Files) {
    $path = [IO.Path]::GetFullPath((Join-Path $extracted $file.Path))
    if (-not $path.StartsWith($extracted + '\', [StringComparison]::OrdinalIgnoreCase)) { throw 'Package manifest contains an out-of-folder path.' }
    if (-not (Test-Path -LiteralPath $path -PathType Leaf) -or (Get-Item -LiteralPath $path).Length -ne $file.Bytes -or (Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash -ne $file.SHA256) { throw "Package file mismatch: $($file.Path)" }
}
$unlisted = @(Get-ChildItem -LiteralPath $extracted -File -Recurse -Force | Where-Object { $_.Name -ne 'package-manifest.json' }).Count
if ($unlisted -ne @($manifest.Files).Count) { throw 'Package contains unexpected unlisted files.' }
$runtime = [IO.File]::ReadAllText((Join-Path $extracted 'GitCompass.runtimeconfig.json')) | ConvertFrom-Json
if (-not $runtime.runtimeOptions.includedFrameworks -or $runtime.runtimeOptions.frameworks) { throw 'Package does not declare bundled .NET frameworks.' }
$app = Join-Path $extracted 'GitCompass.exe'
$header = [IO.BinaryReader]::new([IO.File]::OpenRead($app))
try {
    if ($header.ReadUInt16() -ne 0x5A4D) { throw 'Application has no PE header.' }
    $header.BaseStream.Position = 0x3C; $peOffset = $header.ReadInt32(); $header.BaseStream.Position = $peOffset
    if ($header.ReadUInt32() -ne 0x4550 -or $header.ReadUInt16() -ne 0x8664) { throw 'Expected a Windows x64 executable.' }
} finally { $header.Dispose() }
foreach ($scenario in @('first-run', 'missing-git')) {
    $state = Join-Path $testRoot ('state-' + $scenario)
    New-Item -ItemType Directory -Path $state -Force | Out-Null
    if ($scenario -eq 'missing-git') {
        $settings = @{ SchemaVersion = 1; Theme = 'Light'; GitExecutablePath = (Join-Path $testRoot 'missing-git.exe'); FetchIntervalMinutes = 5 } | ConvertTo-Json
        [IO.File]::WriteAllText((Join-Path $state 'settings.json'), $settings, [Text.UTF8Encoding]::new($false))
    }
    $capture = Join-Path $testRoot ($scenario + '.png')
    $start = [Diagnostics.ProcessStartInfo]::new($app)
    $start.UseShellExecute = $false; $start.CreateNoWindow = $true; $start.WorkingDirectory = $extracted
    # The executable must use its bundled runtime. No development runtime is offered as fallback.
    foreach ($name in @('DOTNET_ROOT', 'DOTNET_ROOT_X64', 'DOTNET_ROOT(x86)', 'DOTNET_HOST_PATH')) { $start.EnvironmentVariables.Remove($name) }
    # These paths are generated by this script and cannot contain quotes.
    $start.Arguments = '--smoke --capture "' + $capture + '" --state-root "' + $state + '" --theme Light'
    $process = [Diagnostics.Process]::Start($start)
    try {
        if (-not $process.WaitForExit(30000)) { $process.Kill(); throw "Package startup timed out: $scenario" }
        if ($process.ExitCode -ne 0 -or -not (Test-Path -LiteralPath $capture)) {
            $diagnostic = [IO.Path]::ChangeExtension($capture, '.error.txt')
            $detail = if (Test-Path -LiteralPath $diagnostic) { [IO.File]::ReadAllText($diagnostic) } else { 'No startup diagnostic was produced.' }
            throw "Package startup failed: $scenario. $detail"
        }
    } finally { $process.Dispose() }
}
$report = [ordered]@{ VerifiedUtc = [DateTimeOffset]::UtcNow.ToString('O'); Zip = $zip; SHA256 = $expected; ManifestFiles = @($manifest.Files).Count; Extracted = $extracted; Runtime = 'self-contained, development runtime variables removed'; StartupScenarios = @('first-run', 'missing-git'); Result = 'passed' }
[IO.File]::WriteAllText((Join-Path $testRoot 'verification.json'), ($report | ConvertTo-Json -Depth 5), [Text.UTF8Encoding]::new($false))
$report | ConvertTo-Json -Depth 5
